#!/usr/bin/env python3
"""Regenerate gallery.js and gallery.json from unique photos, including local previews."""
from pathlib import Path
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
PHOTOS = ROOT / 'photos'
COVER = 'cover.jpg'
SEQUENCE = ['FB_IMG_1792178908223.jpg', 'FB_IMG_1792178854679.jpg']
SUPPORTED = {'.jpg', '.jpeg', '.png', '.webp', '.avif'}

candidates = sorted((p for p in PHOTOS.iterdir()
                    if p.is_file() and p.suffix.lower() in SUPPORTED),
                    key=lambda p: p.name.casefold())

unique = {}
duplicates = []
# Give hero and paired pictures priority over other copies.
priority = {COVER: -2, SEQUENCE[0]: -1, SEQUENCE[1]: 0}
for p in sorted(candidates, key=lambda p: (priority.get(p.name, 1), p.name)):
    digest = hashlib.sha256(p.read_bytes()).hexdigest()
    if digest in unique:
        duplicates.append((p.name, unique[digest].name))
    else:
        unique[digest] = p

unique_names = {p.name for p in unique.values()}
missing_pair = [name for name in SEQUENCE if name not in unique_names]

moments = []
for p in sorted(unique.values(), key=lambda p: p.name.casefold()):
    if p.name == COVER or p.name in SEQUENCE:
        continue
    moments.append({'type':'photo', 'images':[f'photos/{p.name}']})

if not missing_pair:
    moments.append({'type':'pair', 'images':[f'photos/{p}' for p in SEQUENCE]})
else:
    print('Pair intentionally omitted because missing:', ', '.join(missing_pair))

output = {'cover':f'photos/{COVER}', 'moments':moments}
(ROOT/'gallery.json').write_text(json.dumps(output,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
# A normal JavaScript file also works when index.html is opened directly via file://.
# Browser fetch() of a local JSON file is blocked by many browsers.
js = '// Generated by scripts/build_gallery.py; edit photos/, not this file.\n' + 'window.WEDDING_GALLERY = ' + json.dumps(output,ensure_ascii=False,indent=2) + ';\n'
(ROOT/'gallery.js').write_text(js,encoding='utf-8')
print(f'Created gallery.js + gallery.json: {len(unique)} unique photos, {len(moments)} story moments.')
for duplicate,original in duplicates:
    print(f'Skipped exact duplicate {duplicate!r} (same image as {original!r})')
